/** Translate one term (muscle, progression item...). Unknown terms pass through. */
export function tr(term: string, locale: Locale): string {
  if (locale !== 'en') return term;
  return EXERCISE_TERM_EN[term] ?? MUSCLE_GROUP_EN[term] ?? term;
}

export function localizeList(list: string[] | undefined, locale: Locale): string[] {
  if (!list) return [];
  if (locale !== 'en') return list;
  return list.map((t) => EXERCISE_TERM_EN[t] ?? MUSCLE_GROUP_EN[t] ?? t);
}

export function localizeNote(note: string | undefined, locale: Locale): string | undefined {
  if (!note || locale !== 'en') return note;
  return WORKOUT_NOTE_EN[note] ?? note;
}
